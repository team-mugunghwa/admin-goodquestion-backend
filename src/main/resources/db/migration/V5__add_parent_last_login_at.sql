-- ============================================================
-- 보호자 마지막 접속 시각
--
-- V2에서 last_login_ip로 "어디서"는 남겼는데 "언제"가 빠져 있었다. 회원 관리에서
-- "이 보호자가 마지막으로 언제 왔는가"를 답하려면 시각이 있어야 한다.
--
-- 값을 채우는 쪽은 서비스 백엔드다. 로그인(이메일/소셜/가입)과 리프레시 토큰
-- 재발급이 갱신한다. 콘솔은 읽기만 한다.
-- goodquestion-backend의 V20__add_parent_last_login_at.sql에 같은 내용이 들어 있다.
--
-- V2와 같은 이유로 if not exists를 건다. 두 앱이 같은 DB에 각자 Flyway를 돌리므로
-- 먼저 뜬 쪽이 컬럼을 만들고 나중 쪽은 건너뛴다.
-- ============================================================

alter table parents add column if not exists last_login_at timestamptz;
